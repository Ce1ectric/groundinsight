def text(language: str, key: str, **values: object) -> str:
    """
    The text of ``key`` in ``language``, with ``{placeholders}`` filled in.

    Parameters
    ----------
    language : {"de", "en"}
        The language.
    key : str
        A key of :data:`STRINGS`.
    **values
        Values for the placeholders.

    Returns
    -------
    str
        The text.

    Raises
    ------
    KeyError
        For an unknown key -- a missing text is a bug, not a fallback.
    """
    template = STRINGS[language][key]
    return template.format(**values) if values else template


def column_label(language: str, column: str, unit: Optional[str] = None) -> str:
    """
    The header of a table column.

    Parameters
    ----------
    language : {"de", "en"}
        The language.
    column : str
        The library's column name.
    unit : str, optional
        The display unit, appended in brackets.

    Returns
    -------
    str
        The header text; a column without a label shows its name with
        spaces for the underscores and its unit suffix in brackets (a header
        is read by people, not code).
    """
    label = COLUMN_LABELS[language].get(column)
    if label is None:
        label = _readable(column)
    return f"{label} [{unit}]" if unit else label


#: Unit suffixes of the library's column names and how a header writes them.
_UNIT_SUFFIXES = {"V": "V", "A": "A", "Ohm": "Ω", "deg": "°", "degree": "°", "Hz": "Hz", "s": "s",
                  "km": "km", "mm2": "mm²", "C": "°C", "pct": "%"}


def _readable(column: str) -> str:
    """
    A header for a column without a label: words, and the unit in brackets.

    Parameters
    ----------
    column : str
        The library's column name, e.g. ``Z_driving_point_Ohm``.

    Returns
    -------
    str
        ``"Z driving point [Ω]"``; a name without a unit suffix just gets
        spaces for its underscores.
    """
    parts = column.split("_")
    if len(parts) > 1 and parts[-1] in _UNIT_SUFFIXES:
        return f"{' '.join(parts[:-1])} [{_UNIT_SUFFIXES[parts[-1]]}]"
    return " ".join(parts)


def template_label(language: str, name: str) -> str:
    """
    The name of a project template as people read it.

    Parameters
    ----------
    language : {"de", "en"}
        The language.
    name : str
        The template's key (``"mv_ring"``).

    Returns
    -------
    str
        ``STRINGS[language]["template_name_<name>"]`` if there is one, else
        the key with spaces for the underscores.

    Examples
    --------
    >>> template_label("de", "mv_ring"), template_label("en", "my_feeder")
    ('MS-Ring', 'my feeder')
    """
    return STRINGS[language].get(f"template_name_{name}", name.replace("_", " "))


def missing_keys() -> List[str]:
    """
    Keys that exist in one language but not in the other.

    Returns
    -------
    list of str
        ``"<language>:<key>"`` per gap; empty when the tables are complete.
    """
    missing: List[str] = []
    for tables in (STRINGS, COLUMN_LABELS):
        every_key = set().union(*(table.keys() for table in tables.values()))
        for language in LANGUAGES:
            missing += [f"{language}:{key}" for key in sorted(every_key - tables[language].keys())]
    return missing
